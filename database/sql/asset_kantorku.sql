-- b) Aset: tidak boleh hard-delete; status DISPOSED bersifat final
CREATE OR REPLACE FUNCTION fn_assets_guard() RETURNS trigger AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'Aset % tidak boleh dihapus dari database', OLD.asset_tag
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;
    IF OLD.status = 'DISPOSED' AND NEW.status IS DISTINCT FROM 'DISPOSED' THEN
        RAISE EXCEPTION 'Aset % sudah DISPOSED; status final tidak dapat diubah', OLD.asset_tag
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_assets_guard
    BEFORE UPDATE OR DELETE ON assets
    FOR EACH ROW EXECUTE FUNCTION fn_assets_guard();

-- c) Approval step: keputusan immutable; approver harus berbeda dari requester
CREATE OR REPLACE FUNCTION fn_approval_steps_guard() RETURNS trigger AS $$
DECLARE
    v_requester BIGINT;
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'Approval step tidak boleh dihapus' USING ERRCODE = 'integrity_constraint_violation';
    END IF;

    IF TG_OP = 'UPDATE' THEN
        IF OLD.status <> 'PENDING' THEN
            RAISE EXCEPTION 'Keputusan approval step % sudah final', OLD.id
                USING ERRCODE = 'integrity_constraint_violation';
        END IF;
        IF NEW.approver_employee_id <> OLD.approver_employee_id THEN
            RAISE EXCEPTION 'Snapshot approver tidak boleh diubah' USING ERRCODE = 'integrity_constraint_violation';
        END IF;
    END IF;

    SELECT requester_employee_id INTO v_requester FROM approval_requests WHERE id = NEW.approval_request_id;
    IF v_requester = NEW.approver_employee_id THEN
        RAISE EXCEPTION 'Approver tidak boleh sama dengan requester' USING ERRCODE = 'check_violation';
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_approval_steps_guard
    BEFORE INSERT OR UPDATE OR DELETE ON approval_steps
    FOR EACH ROW EXECUTE FUNCTION fn_approval_steps_guard();

-- d) Approval request yang sudah final (APPROVED/REJECTED/CANCELLED) tidak boleh berubah status
CREATE OR REPLACE FUNCTION fn_approval_requests_guard() RETURNS trigger AS $$
BEGIN
    IF OLD.status IN ('APPROVED', 'REJECTED', 'CANCELLED') AND NEW.status IS DISTINCT FROM OLD.status THEN
        RAISE EXCEPTION 'Approval request % sudah final (%)', OLD.id, OLD.status
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_approval_requests_guard
    BEFORE UPDATE ON approval_requests
    FOR EACH ROW EXECUTE FUNCTION fn_approval_requests_guard();

-- e) Satu aset tidak boleh memiliki assignment aktif DAN loan aktif bersamaan
CREATE OR REPLACE FUNCTION fn_asset_assignment_loan_exclusive() RETURNS trigger AS $$
BEGIN
    IF TG_TABLE_NAME = 'asset_assignments' AND NEW.returned_at IS NULL THEN
        IF EXISTS (SELECT 1 FROM asset_loans WHERE asset_id = NEW.asset_id AND status IN ('CHECKED_OUT', 'OVERDUE')) THEN
            RAISE EXCEPTION 'Aset % sedang dipinjam; tidak dapat di-assign', NEW.asset_id
                USING ERRCODE = 'check_violation';
        END IF;
    ELSIF TG_TABLE_NAME = 'asset_loans' AND NEW.status IN ('CHECKED_OUT', 'OVERDUE') THEN
        IF EXISTS (SELECT 1 FROM asset_assignments WHERE asset_id = NEW.asset_id AND returned_at IS NULL) THEN
            RAISE EXCEPTION 'Aset % sedang ditugaskan; tidak dapat dipinjam', NEW.asset_id
                USING ERRCODE = 'check_violation';
        END IF;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_asset_assignments_exclusive
    BEFORE INSERT OR UPDATE ON asset_assignments
    FOR EACH ROW EXECUTE FUNCTION fn_asset_assignment_loan_exclusive();

CREATE TRIGGER trg_asset_loans_exclusive
    BEFORE INSERT OR UPDATE ON asset_loans
    FOR EACH ROW EXECUTE FUNCTION fn_asset_assignment_loan_exclusive();

