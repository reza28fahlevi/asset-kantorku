-- =============================================================================
--  ASSET KANTORKU — Skema Database PostgreSQL (>= 13)
--  Laravel 13 monolith · RBAC · Procurement → Assignment/Loan → Disposal
--
--  Cara pakai:
--    createdb -U postgres asset_kantorku
--    psql -U postgres -d asset_kantorku -f database/sql/asset_kantorku.sql
--
--  File ini membuat seluruh tabel (termasuk tabel bawaan Laravel: sessions,
--  cache, jobs, notifications), constraint, trigger integritas, data RBAC, dan
--  data awal (demo). Jalankan pada database KOSONG.
--
--  Akun demo (password: "password") — WAJIB diganti setelah instalasi:
--    sysadmin@kantorku.test   → System Administrator
--    admin.aset@kantorku.test → Asset Administrator
--    direktur@kantorku.test   → Manager (approver eskalasi)
--    manager.it@kantorku.test → Manager
--    staff@kantorku.test      → Staff
--    auditor@kantorku.test    → Auditor
-- =============================================================================

BEGIN;

SET client_min_messages = warning;

-- Dibutuhkan untuk exclusion constraint (asset_id WITH =, range WITH &&)
CREATE EXTENSION IF NOT EXISTS btree_gist;

-- =============================================================================
-- 1. TABEL FRAMEWORK LARAVEL
-- =============================================================================

CREATE TABLE sessions (
    id              VARCHAR(255) PRIMARY KEY,
    user_id         BIGINT NULL,
    ip_address      VARCHAR(45) NULL,
    user_agent      TEXT NULL,
    payload         TEXT NOT NULL,
    last_activity   INTEGER NOT NULL
);
CREATE INDEX sessions_user_id_index ON sessions (user_id);
CREATE INDEX sessions_last_activity_index ON sessions (last_activity);

CREATE TABLE password_reset_tokens (
    email       VARCHAR(255) PRIMARY KEY,
    token       VARCHAR(255) NOT NULL,
    created_at  TIMESTAMP(0) NULL
);

CREATE TABLE cache (
    key         VARCHAR(255) PRIMARY KEY,
    value       TEXT NOT NULL,
    expiration  BIGINT NOT NULL
);
CREATE INDEX cache_expiration_index ON cache (expiration);

CREATE TABLE cache_locks (
    key         VARCHAR(255) PRIMARY KEY,
    owner       VARCHAR(255) NOT NULL,
    expiration  BIGINT NOT NULL
);
CREATE INDEX cache_locks_expiration_index ON cache_locks (expiration);

CREATE TABLE jobs (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    queue         VARCHAR(255) NOT NULL,
    payload       TEXT NOT NULL,
    attempts      SMALLINT NOT NULL,
    reserved_at   INTEGER NULL,
    available_at  INTEGER NOT NULL,
    created_at    INTEGER NOT NULL
);
CREATE INDEX jobs_queue_index ON jobs (queue);

CREATE TABLE job_batches (
    id              VARCHAR(255) PRIMARY KEY,
    name            VARCHAR(255) NOT NULL,
    total_jobs      INTEGER NOT NULL,
    pending_jobs    INTEGER NOT NULL,
    failed_jobs     INTEGER NOT NULL,
    failed_job_ids  TEXT NOT NULL,
    options         TEXT NULL,
    cancelled_at    INTEGER NULL,
    created_at      INTEGER NOT NULL,
    finished_at     INTEGER NULL
);

CREATE TABLE failed_jobs (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid        VARCHAR(255) NOT NULL UNIQUE,
    connection  TEXT NOT NULL,
    queue       TEXT NOT NULL,
    payload     TEXT NOT NULL,
    exception   TEXT NOT NULL,
    failed_at   TIMESTAMP(0) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX failed_jobs_connection_queue_failed_at_index ON failed_jobs (connection, queue, failed_at);

-- Notifikasi in-app (Laravel database channel)
CREATE TABLE notifications (
    id               UUID PRIMARY KEY,
    type             VARCHAR(255) NOT NULL,
    notifiable_type  VARCHAR(255) NOT NULL,
    notifiable_id    BIGINT NOT NULL,
    data             TEXT NOT NULL,
    read_at          TIMESTAMP(0) NULL,
    created_at       TIMESTAMP(0) NULL,
    updated_at       TIMESTAMP(0) NULL
);
CREATE INDEX notifications_notifiable_index ON notifications (notifiable_type, notifiable_id);

-- =============================================================================
-- 2. ORGANISASI: DEPARTEMEN, LOKASI, KARYAWAN
-- =============================================================================

CREATE TABLE departments (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(20)  NOT NULL,
    name        VARCHAR(150) NOT NULL,
    is_active   BOOLEAN NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMP(0) NULL,
    updated_at  TIMESTAMP(0) NULL,
    deleted_at  TIMESTAMP(0) NULL
);
CREATE UNIQUE INDEX departments_code_unique ON departments (code) WHERE deleted_at IS NULL;

CREATE TABLE locations (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(20)  NOT NULL,
    name        VARCHAR(150) NOT NULL,
    address     TEXT NULL,
    parent_id   BIGINT NULL REFERENCES locations (id),
    is_active   BOOLEAN NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMP(0) NULL,
    updated_at  TIMESTAMP(0) NULL,
    deleted_at  TIMESTAMP(0) NULL,
    CONSTRAINT locations_parent_not_self CHECK (parent_id IS NULL OR parent_id <> id)
);
CREATE UNIQUE INDEX locations_code_unique ON locations (code) WHERE deleted_at IS NULL;
CREATE INDEX locations_parent_id_index ON locations (parent_id);

-- Master karyawan: sumber resmi identitas & struktur organisasi (approver = atasan langsung)
CREATE TABLE employees (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_no          VARCHAR(30)  NOT NULL UNIQUE,
    name                 VARCHAR(150) NOT NULL,
    email                VARCHAR(150) NULL UNIQUE,
    phone                VARCHAR(30)  NULL,
    department_id        BIGINT NOT NULL REFERENCES departments (id),
    manager_employee_id  BIGINT NULL REFERENCES employees (id),
    job_title            VARCHAR(100) NULL,
    employment_status    VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    start_date           DATE NULL,
    end_date             DATE NULL,
    work_location_id     BIGINT NULL REFERENCES locations (id),
    created_at           TIMESTAMP(0) NULL,
    updated_at           TIMESTAMP(0) NULL,
    CONSTRAINT employees_status_check CHECK (employment_status IN ('ACTIVE', 'ON_LEAVE', 'INACTIVE')),
    CONSTRAINT employees_manager_not_self CHECK (manager_employee_id IS NULL OR manager_employee_id <> id),
    CONSTRAINT employees_dates_check CHECK (end_date IS NULL OR start_date IS NULL OR end_date >= start_date)
);
CREATE INDEX employees_department_id_index ON employees (department_id);
CREATE INDEX employees_manager_employee_id_index ON employees (manager_employee_id);
CREATE INDEX employees_status_index ON employees (employment_status);

-- =============================================================================
-- 3. IDENTITAS & RBAC
-- =============================================================================

-- Akun login; opsional ditautkan ke tepat satu karyawan
CREATE TABLE users (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id        BIGINT NULL UNIQUE REFERENCES employees (id),
    name               VARCHAR(150) NOT NULL,
    email              VARCHAR(150) NOT NULL UNIQUE,
    email_verified_at  TIMESTAMP(0) NULL,
    password           VARCHAR(255) NOT NULL,
    is_active          BOOLEAN NOT NULL DEFAULT TRUE,
    last_login_at      TIMESTAMP(0) NULL,
    remember_token     VARCHAR(100) NULL,
    created_at         TIMESTAMP(0) NULL,
    updated_at         TIMESTAMP(0) NULL
);

CREATE TABLE roles (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(50)  NOT NULL UNIQUE,   -- slug, dipakai di kode
    display_name  VARCHAR(100) NOT NULL,
    description   TEXT NULL,
    is_system     BOOLEAN NOT NULL DEFAULT FALSE, -- role bawaan: tidak boleh dihapus
    created_at    TIMESTAMP(0) NULL,
    updated_at    TIMESTAMP(0) NULL
);

CREATE TABLE permissions (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(100) NOT NULL UNIQUE,   -- contoh: asset.view
    display_name  VARCHAR(150) NOT NULL,
    group_name    VARCHAR(50)  NOT NULL,
    description   TEXT NULL,
    created_at    TIMESTAMP(0) NULL,
    updated_at    TIMESTAMP(0) NULL
);

CREATE TABLE permission_role (
    permission_id  BIGINT NOT NULL REFERENCES permissions (id) ON DELETE CASCADE,
    role_id        BIGINT NOT NULL REFERENCES roles (id) ON DELETE CASCADE,
    PRIMARY KEY (permission_id, role_id)
);
CREATE INDEX permission_role_role_id_index ON permission_role (role_id);

CREATE TABLE role_user (
    role_id  BIGINT NOT NULL REFERENCES roles (id) ON DELETE CASCADE,
    user_id  BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    PRIMARY KEY (role_id, user_id)
);
CREATE INDEX role_user_user_id_index ON role_user (user_id);

-- Konfigurasi aplikasi (mis. approver eskalasi)
CREATE TABLE settings (
    key          VARCHAR(100) PRIMARY KEY,
    value        TEXT NULL,
    description  TEXT NULL,
    updated_at   TIMESTAMP(0) NULL
);

-- Penomoran dokumen aman-konkurensi (SELECT ... FOR UPDATE)
CREATE TABLE number_sequences (
    key         VARCHAR(50) PRIMARY KEY,
    last_value  BIGINT NOT NULL DEFAULT 0,
    updated_at  TIMESTAMP(0) NULL
);

-- =============================================================================
-- 4. MASTER ASET: KATEGORI & VENDOR
-- =============================================================================

CREATE TABLE asset_categories (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                VARCHAR(10)  NOT NULL,   -- prefix asset tag, mis. LPT
    name                VARCHAR(150) NOT NULL,
    description         TEXT NULL,
    useful_life_months  INTEGER NULL CHECK (useful_life_months IS NULL OR useful_life_months > 0),
    requires_serial     BOOLEAN NOT NULL DEFAULT FALSE,
    is_active           BOOLEAN NOT NULL DEFAULT TRUE,
    created_at          TIMESTAMP(0) NULL,
    updated_at          TIMESTAMP(0) NULL,
    deleted_at          TIMESTAMP(0) NULL
);
CREATE UNIQUE INDEX asset_categories_code_unique ON asset_categories (code) WHERE deleted_at IS NULL;

CREATE TABLE vendors (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            VARCHAR(20)  NOT NULL,
    name            VARCHAR(150) NOT NULL,
    contact_person  VARCHAR(100) NULL,
    phone           VARCHAR(30)  NULL,
    email           VARCHAR(150) NULL,
    address         TEXT NULL,
    tax_number      VARCHAR(30)  NULL,
    notes           TEXT NULL,
    is_active       BOOLEAN NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMP(0) NULL,
    updated_at      TIMESTAMP(0) NULL,
    deleted_at      TIMESTAMP(0) NULL
);
CREATE UNIQUE INDEX vendors_code_unique ON vendors (code) WHERE deleted_at IS NULL;

-- =============================================================================
-- 5. APPROVAL (entitas bersama untuk semua jenis permintaan)
-- =============================================================================

CREATE TABLE approval_requests (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_type           VARCHAR(20) NOT NULL,
    requester_employee_id  BIGINT NOT NULL REFERENCES employees (id),
    submitted_by_user_id   BIGINT NULL REFERENCES users (id),
    status                 VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    submitted_at           TIMESTAMP(0) NULL,
    closed_at              TIMESTAMP(0) NULL,
    created_at             TIMESTAMP(0) NULL,
    updated_at             TIMESTAMP(0) NULL,
    CONSTRAINT approval_requests_type_check CHECK (request_type IN ('PROCUREMENT', 'ASSIGNMENT', 'LOAN', 'LOAN_EXTENSION', 'DISPOSAL')),
    CONSTRAINT approval_requests_status_check CHECK (status IN ('DRAFT', 'PENDING', 'APPROVED', 'REJECTED', 'CANCELLED'))
);
CREATE INDEX approval_requests_status_index ON approval_requests (status);
CREATE INDEX approval_requests_requester_index ON approval_requests (requester_employee_id);

CREATE TABLE approval_steps (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    approval_request_id   BIGINT NOT NULL REFERENCES approval_requests (id),
    step_order            SMALLINT NOT NULL DEFAULT 1,
    approver_employee_id  BIGINT NOT NULL REFERENCES employees (id),  -- snapshot saat submit
    approver_source       VARCHAR(20) NOT NULL DEFAULT 'MANAGER',
    status                VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    comment               TEXT NULL,
    decided_at            TIMESTAMP(0) NULL,
    decided_by_user_id    BIGINT NULL REFERENCES users (id),
    created_at            TIMESTAMP(0) NULL,
    updated_at            TIMESTAMP(0) NULL,
    CONSTRAINT approval_steps_order_unique UNIQUE (approval_request_id, step_order),
    CONSTRAINT approval_steps_source_check CHECK (approver_source IN ('MANAGER', 'ESCALATION')),
    CONSTRAINT approval_steps_status_check CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'CANCELLED')),
    CONSTRAINT approval_steps_reject_comment CHECK (status <> 'REJECTED' OR (comment IS NOT NULL AND length(trim(comment)) > 0)),
    CONSTRAINT approval_steps_decided_check CHECK (status IN ('PENDING', 'CANCELLED') OR decided_at IS NOT NULL)
);
CREATE INDEX approval_steps_approver_status_index ON approval_steps (approver_employee_id, status);

-- =============================================================================
-- 6. PROCUREMENT
-- =============================================================================

CREATE TABLE procurement_requests (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_no             VARCHAR(30) NOT NULL UNIQUE,
    approval_request_id    BIGINT NULL UNIQUE REFERENCES approval_requests (id),
    requester_employee_id  BIGINT NOT NULL REFERENCES employees (id),
    created_by_user_id     BIGINT NULL REFERENCES users (id),
    department_id          BIGINT NOT NULL REFERENCES departments (id),
    title                  VARCHAR(200) NOT NULL,
    justification          TEXT NOT NULL,
    needed_by              DATE NULL,
    estimated_total        NUMERIC(18, 2) NOT NULL DEFAULT 0,
    status                 VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    vendor_id              BIGINT NULL REFERENCES vendors (id),
    po_number              VARCHAR(50) NULL,
    ordered_at             TIMESTAMP(0) NULL,
    ordered_by_user_id     BIGINT NULL REFERENCES users (id),
    submitted_at           TIMESTAMP(0) NULL,
    completed_at           TIMESTAMP(0) NULL,
    closing_note           TEXT NULL,
    cancelled_at           TIMESTAMP(0) NULL,
    created_at             TIMESTAMP(0) NULL,
    updated_at             TIMESTAMP(0) NULL,
    CONSTRAINT procurement_requests_status_check CHECK (status IN
        ('DRAFT', 'PENDING_APPROVAL', 'REJECTED', 'APPROVED', 'ORDERED', 'PARTIALLY_RECEIVED', 'RECEIVED', 'CANCELLED')),
    CONSTRAINT procurement_requests_total_check CHECK (estimated_total >= 0)
);
CREATE INDEX procurement_requests_status_index ON procurement_requests (status);
CREATE INDEX procurement_requests_requester_index ON procurement_requests (requester_employee_id);

CREATE TABLE procurement_request_items (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    procurement_request_id  BIGINT NOT NULL REFERENCES procurement_requests (id) ON DELETE CASCADE,
    asset_category_id       BIGINT NOT NULL REFERENCES asset_categories (id),
    item_name               VARCHAR(200) NOT NULL,
    specification           TEXT NULL,
    quantity                INTEGER NOT NULL,
    estimated_unit_price    NUMERIC(18, 2) NOT NULL DEFAULT 0,
    quantity_received       INTEGER NOT NULL DEFAULT 0,
    quantity_rejected       INTEGER NOT NULL DEFAULT 0,
    created_at              TIMESTAMP(0) NULL,
    updated_at              TIMESTAMP(0) NULL,
    CONSTRAINT pri_quantity_check CHECK (quantity > 0),
    CONSTRAINT pri_price_check CHECK (estimated_unit_price >= 0),
    CONSTRAINT pri_received_check CHECK (quantity_received >= 0 AND quantity_received <= quantity),
    CONSTRAINT pri_rejected_check CHECK (quantity_rejected >= 0)
);
CREATE INDEX procurement_request_items_request_index ON procurement_request_items (procurement_request_id);

-- Penerimaan barang (bisa bertahap / parsial)
CREATE TABLE procurement_receipts (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receipt_no              VARCHAR(30) NOT NULL UNIQUE,
    procurement_request_id  BIGINT NOT NULL REFERENCES procurement_requests (id),
    received_at             TIMESTAMP(0) NOT NULL,
    received_by_user_id     BIGINT NULL REFERENCES users (id),
    delivery_note_no        VARCHAR(50) NULL,
    notes                   TEXT NULL,
    created_at              TIMESTAMP(0) NULL,
    updated_at              TIMESTAMP(0) NULL
);
CREATE INDEX procurement_receipts_request_index ON procurement_receipts (procurement_request_id);

CREATE TABLE procurement_receipt_items (
    id                           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    procurement_receipt_id       BIGINT NOT NULL REFERENCES procurement_receipts (id) ON DELETE CASCADE,
    procurement_request_item_id  BIGINT NOT NULL REFERENCES procurement_request_items (id),
    quantity_accepted            INTEGER NOT NULL DEFAULT 0 CHECK (quantity_accepted >= 0),
    quantity_rejected            INTEGER NOT NULL DEFAULT 0 CHECK (quantity_rejected >= 0),
    exception_notes              TEXT NULL,   -- selisih / kerusakan
    created_at                   TIMESTAMP(0) NULL,
    updated_at                   TIMESTAMP(0) NULL
);

-- =============================================================================
-- 7. ASSET REGISTRY
-- =============================================================================

CREATE TABLE assets (
    id                           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_tag                    VARCHAR(50)  NOT NULL UNIQUE,
    name                         VARCHAR(200) NOT NULL,
    asset_category_id            BIGINT NOT NULL REFERENCES asset_categories (id),
    procurement_request_item_id  BIGINT NULL REFERENCES procurement_request_items (id),
    procurement_receipt_id       BIGINT NULL REFERENCES procurement_receipts (id),
    vendor_id                    BIGINT NULL REFERENCES vendors (id),
    department_id                BIGINT NULL REFERENCES departments (id),
    location_id                  BIGINT NOT NULL REFERENCES locations (id),
    brand                        VARCHAR(100) NULL,
    model                        VARCHAR(100) NULL,
    serial_number                VARCHAR(100) NULL,
    specification                TEXT NULL,
    status                       VARCHAR(20) NOT NULL DEFAULT 'AVAILABLE',
    condition                    VARCHAR(20) NOT NULL DEFAULT 'GOOD',
    purchase_date                DATE NULL,
    purchase_cost                NUMERIC(18, 2) NULL CHECK (purchase_cost IS NULL OR purchase_cost >= 0),
    warranty_end_date            DATE NULL,
    notes                        TEXT NULL,
    created_at                   TIMESTAMP(0) NULL,
    updated_at                   TIMESTAMP(0) NULL,
    CONSTRAINT assets_status_check CHECK (status IN
        ('AVAILABLE', 'ASSIGNED', 'ON_LOAN', 'IN_REPAIR', 'PENDING_DISPOSAL', 'DISPOSED', 'LOST')),
    CONSTRAINT assets_condition_check CHECK (condition IN ('GOOD', 'FAIR', 'POOR', 'DAMAGED'))
);
CREATE UNIQUE INDEX assets_serial_number_unique ON assets (serial_number) WHERE serial_number IS NOT NULL;
CREATE INDEX assets_status_index ON assets (status);
CREATE INDEX assets_category_index ON assets (asset_category_id);
CREATE INDEX assets_location_index ON assets (location_id);

-- Histori domain aset (append-only)
CREATE TABLE asset_events (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_id                  BIGINT NOT NULL REFERENCES assets (id),
    event_type                VARCHAR(40) NOT NULL,
    from_status               VARCHAR(20) NULL,
    to_status                 VARCHAR(20) NULL,
    from_location_id          BIGINT NULL REFERENCES locations (id),
    to_location_id            BIGINT NULL REFERENCES locations (id),
    related_employee_id       BIGINT NULL REFERENCES employees (id),  -- penerima / peminjam
    performed_by_employee_id  BIGINT NULL REFERENCES employees (id),
    performed_by_user_id      BIGINT NULL REFERENCES users (id),
    reference_type            VARCHAR(40) NULL,
    reference_id              BIGINT NULL,
    notes                     TEXT NULL,
    metadata                  JSONB NULL,
    occurred_at               TIMESTAMP(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at                TIMESTAMP(0) NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX asset_events_asset_occurred_index ON asset_events (asset_id, occurred_at DESC);

-- =============================================================================
-- 8. ASSIGNMENT (penugasan jangka panjang)
-- =============================================================================

CREATE TABLE assignment_requests (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_no             VARCHAR(30) NOT NULL UNIQUE,
    approval_request_id    BIGINT NULL UNIQUE REFERENCES approval_requests (id),
    requester_employee_id  BIGINT NOT NULL REFERENCES employees (id),
    created_by_user_id     BIGINT NULL REFERENCES users (id),
    recipient_employee_id  BIGINT NOT NULL REFERENCES employees (id),
    location_id            BIGINT NOT NULL REFERENCES locations (id),
    purpose                TEXT NOT NULL,
    start_date             DATE NOT NULL,
    status                 VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    submitted_at           TIMESTAMP(0) NULL,
    fulfilled_at           TIMESTAMP(0) NULL,
    cancelled_at           TIMESTAMP(0) NULL,
    created_at             TIMESTAMP(0) NULL,
    updated_at             TIMESTAMP(0) NULL,
    CONSTRAINT assignment_requests_status_check CHECK (status IN
        ('DRAFT', 'PENDING_APPROVAL', 'REJECTED', 'APPROVED', 'FULFILLED', 'CANCELLED'))
);
CREATE INDEX assignment_requests_status_index ON assignment_requests (status);

CREATE TABLE assignment_request_items (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assignment_request_id  BIGINT NOT NULL REFERENCES assignment_requests (id) ON DELETE CASCADE,
    asset_id               BIGINT NOT NULL REFERENCES assets (id),
    created_at             TIMESTAMP(0) NULL,
    updated_at             TIMESTAMP(0) NULL,
    CONSTRAINT assignment_request_items_unique UNIQUE (assignment_request_id, asset_id)
);
CREATE INDEX assignment_request_items_asset_index ON assignment_request_items (asset_id);

CREATE TABLE asset_assignments (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_id               BIGINT NOT NULL REFERENCES assets (id),
    employee_id            BIGINT NOT NULL REFERENCES employees (id),
    assignment_request_id  BIGINT NULL REFERENCES assignment_requests (id),
    location_id            BIGINT NULL REFERENCES locations (id),
    assigned_at            TIMESTAMP(0) NOT NULL,
    assigned_by_user_id    BIGINT NULL REFERENCES users (id),
    condition_out          VARCHAR(20) NOT NULL,
    handover_document_no   VARCHAR(50) NULL,
    handover_notes         TEXT NULL,
    returned_at            TIMESTAMP(0) NULL,
    returned_by_user_id    BIGINT NULL REFERENCES users (id),
    condition_in           VARCHAR(20) NULL,
    return_notes           TEXT NULL,
    created_at             TIMESTAMP(0) NULL,
    updated_at             TIMESTAMP(0) NULL,
    CONSTRAINT asset_assignments_cond_out_check CHECK (condition_out IN ('GOOD', 'FAIR', 'POOR', 'DAMAGED')),
    CONSTRAINT asset_assignments_cond_in_check CHECK (condition_in IS NULL OR condition_in IN ('GOOD', 'FAIR', 'POOR', 'DAMAGED')),
    CONSTRAINT asset_assignments_dates_check CHECK (returned_at IS NULL OR returned_at >= assigned_at)
);
-- Satu aset maksimal satu assignment aktif
CREATE UNIQUE INDEX asset_assignments_one_active ON asset_assignments (asset_id) WHERE returned_at IS NULL;
CREATE INDEX asset_assignments_employee_index ON asset_assignments (employee_id);

-- =============================================================================
-- 9. PEMINJAMAN ASET (LOAN)
-- =============================================================================

CREATE TABLE asset_loan_requests (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_no             VARCHAR(30) NOT NULL UNIQUE,
    approval_request_id    BIGINT NULL UNIQUE REFERENCES approval_requests (id),
    requester_employee_id  BIGINT NOT NULL REFERENCES employees (id),
    created_by_user_id     BIGINT NULL REFERENCES users (id),
    borrower_employee_id   BIGINT NOT NULL REFERENCES employees (id),
    usage_location_id      BIGINT NULL REFERENCES locations (id),
    purpose                TEXT NOT NULL,
    start_date             DATE NOT NULL,
    due_date               DATE NOT NULL,
    status                 VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    submitted_at           TIMESTAMP(0) NULL,
    fulfilled_at           TIMESTAMP(0) NULL,
    cancelled_at           TIMESTAMP(0) NULL,
    created_at             TIMESTAMP(0) NULL,
    updated_at             TIMESTAMP(0) NULL,
    CONSTRAINT asset_loan_requests_status_check CHECK (status IN
        ('DRAFT', 'PENDING_APPROVAL', 'REJECTED', 'APPROVED', 'FULFILLED', 'CANCELLED')),
    CONSTRAINT asset_loan_requests_dates_check CHECK (due_date >= start_date)
);
CREATE INDEX asset_loan_requests_status_index ON asset_loan_requests (status);

CREATE TABLE asset_loan_request_items (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_loan_request_id  BIGINT NOT NULL REFERENCES asset_loan_requests (id) ON DELETE CASCADE,
    asset_id               BIGINT NOT NULL REFERENCES assets (id),
    created_at             TIMESTAMP(0) NULL,
    updated_at             TIMESTAMP(0) NULL,
    CONSTRAINT asset_loan_request_items_unique UNIQUE (asset_loan_request_id, asset_id)
);
CREATE INDEX asset_loan_request_items_asset_index ON asset_loan_request_items (asset_id);

CREATE TABLE asset_loans (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_id                BIGINT NOT NULL REFERENCES assets (id),
    borrower_employee_id    BIGINT NOT NULL REFERENCES employees (id),
    asset_loan_request_id   BIGINT NULL REFERENCES asset_loan_requests (id),
    usage_location_id       BIGINT NULL REFERENCES locations (id),
    checked_out_at          TIMESTAMP(0) NOT NULL,
    checked_out_by_user_id  BIGINT NULL REFERENCES users (id),
    due_at                  TIMESTAMP(0) NOT NULL,
    original_due_at         TIMESTAMP(0) NOT NULL,
    returned_at             TIMESTAMP(0) NULL,
    returned_by_user_id     BIGINT NULL REFERENCES users (id),
    condition_out           VARCHAR(20) NOT NULL,
