-- a) Tabel append-only: asset_events & audit_logs tidak boleh diubah/dihapus
CREATE OR REPLACE FUNCTION fn_prevent_modify_append_only() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'Tabel % bersifat append-only: % tidak diizinkan', TG_TABLE_NAME, TG_OP
        USING ERRCODE = 'integrity_constraint_violation';
END;
$$ LANGUAGE plpgsql;

